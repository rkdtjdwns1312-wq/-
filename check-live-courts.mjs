  d=await act('join',{court:0,names:['첫칸','둘째칸','셋째칸']});d=await act('leave',{court:0,slot:1});
  d=await act('join',{court:0,slot:1,names:['다시채움']});assert.deepEqual(d.courts[0].names,['첫칸','다시채움','셋째칸','']);
  d=await act('cancel',{court:0});assert.ok(d.courts[0].names.every(name=>name===''),'waiting court cancellation clears the whole game');
  for(const values of [{court:-1,name:'가'},{court:0,name:''},{court:0,name:'가\n나'},{court:0,name:'가'.repeat(41)}])assert.equal((await call({version:d.version,action:'join',...values})).status,400);
  assert.equal((await call({version:d.version,action:'join',court:'queue',name:'먼저 대기'})).status,409);
  d=await act('join',{court:0,name:'  자유 참가  '});assert.equal(d.courts[0].names[0],'자유 참가');
  await rejectCourtDuplicate(1,'  자유 참가  ');
  await rejectCourtDuplicate('queue','자유 참가');
  d=await act('leave',{court:0,slot:0});assert.equal(d.courts[0].names[0],'');
  await act('join',{court:0,name:'자유 참가'});d=await act('join',{court:0,name:'다른 참가'});
  const race=await Promise.all([call({version:d.version,action:'join',court:0,name:'셋'}),call({version:d.version,action:'join',court:0,name:'넷'})]);
  assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
  d=await read();await act('join',{court:0,name:d.courts[0].names.includes('셋')?'넷':'셋'});
  d=await read();assert.equal(d.courts[0].state,'playing');
  await rejectCourtDuplicate(0,'자유 참가');
  await rejectCourtDuplicate(1,'자유 참가');
  await rejectCourtDuplicate('queue','자유 참가');
  assert.equal((await call({version:d.version,action:'leave',court:0,slot:0})).status,409);
  for(let i=0;i<4;i++)await act('join',{court:1,name:'두번째'+i});
  await act('join',{court:'queue',names:['대기0','대기1','대기2','대기3']});
  await act('join',{court:'queue',names:['대기4','대기5','대기6','대기7']});
  await act('join',{court:'queue',names:['대기8']});
  d=await read();assert.equal(d.queue.length,3);assert.deepEqual(d.queue[0].names,['대기0','대기1','대기2','대기3']);
  assert.deepEqual(d.queue[2].names,['대기8','','','']);
  const retained=JSON.parse(db.prepare('SELECT payload FROM live_courts WHERE id=1').get().payload),openVersion=d.version;
  d=await act('close',{},true);assert.equal(d.isOpen,false);
  for(const key of ['courts','queue','participants'])assert.deepEqual(d[key],[],'closing clears '+key+' even for operators');
  assert.equal(d.version,openVersion+1,'closing clears and locks in one versioned write');
  assert.deepEqual(JSON.parse(db.prepare('SELECT payload FROM live_courts WHERE id=1').get().payload),{courts:[],queue:[],isOpen:false,participants:[]},'empty state is persisted, not merely hidden');
  assert.deepEqual(await act('close',{},true),d,'repeated empty close is idempotent');
  const closedPublic=await read();assert.deepEqual(closedPublic.courts,[]);assert.deepEqual(closedPublic.queue,[]);assert.deepEqual(closedPublic.participants,[]);
  for(const values of [{action:'join',court:0,name:'잠긴 입장'},{action:'join',court:'queue',name:'잠긴 대기'},{action:'leave',court:'queue',group:0,slot:0},{action:'end',court:0}])assert.equal((await call({version:d.version,...values})).status,409);
  assert.equal((await call({version:openVersion,action:'end',court:0})).status,409,'old open tabs cannot act after closure');
  assert.equal((await read(true)).version,d.version,'denied actions must not mutate the closed session');
  d=await act('open',{},true);
  for(const key of ['courts','queue','participants'])assert.deepEqual(d[key],[],'reopening never restores '+key);
  // Restore only this local test fixture to exercise the existing FIFO scenarios.
  db.prepare('UPDATE live_courts SET payload=? WHERE id=1').run(JSON.stringify(retained));d=await read();
  const queueDuplicate=await call({version:d.version,action:'join',court:'queue',name:'대기0'});
  assert.equal(queueDuplicate.status,409);assert.equal((await queueDuplicate.json()).error,'이미 다음 대진에 등록된 이름입니다.');
  d=await act('leave',{court:'queue',group:1,slot:2});assert.equal(d.queue[1].names[2],'');
  d=await act('join',{court:'queue',group:1,slot:2,names:['대기6']});assert.equal(d.queue[1].names[2],'대기6','the plus action refills the exact queue slot');
  await act('cancel',{court:'queue',group:2});d=await read();assert.equal(d.queue.length,2,'waiting game cancellation removes the whole queue group');
  d=await act('end',{court:0});assert.deepEqual(d.courts[0].names,['대기0','대기1','대기2','대기3']);assert.equal(d.queue.length,1);
  assert.equal(d.courts[0].state,'playing');
  assert.ok(!('winner' in d.courts[0]),'free play must not store winners');
  const oldVersion=d.version;
  d=await act('end',{court:1});assert.deepEqual(d.courts[1].names,['대기4','대기5','대기6','대기7']);assert.equal(d.queue.length,0);
  assert.equal((await call({version:oldVersion,action:'end',court:0})).status,409);
  d=await act('end',{court:0});assert.deepEqual(d.courts[0],{names:['','','',''],state:'waiting'});
  assert.equal((await call({version:d.version,action:'end',court:0})).status,409);
  d=await act('join',{court:0,name:'자유 참가'});assert.equal(d.courts[0].names[0],'자유 참가','finished players may join again');
  await act('leave',{court:0,slot:0});
  d=await act('create',{count:2},true);
  const duplicateRace=await Promise.all([call({version:d.version,action:'join',court:0,name:'동시 이름'}),call({version:d.version,action:'join',court:1,name:'동시 이름'})]);
  assert.deepEqual(duplicateRace.map(r=>r.status).sort(),[200,409]);
  assert.equal((await read()).courts.flatMap(c=>c.names).filter(n=>n==='동시 이름').length,1);
  await rejectCourtDuplicate('queue','동시 이름');
  await act('join',{court:0,name:'다음 생성 때 초기화'});
  d=await act('create',{count:1},true);assert.equal(d.courts.length,1);assert.ok(d.courts[0].names.every(n=>n===''));
  const closeRace=await Promise.all([call({version:d.version,action:'close'},true),call({version:d.version,action:'join',court:0,name:'닫힘 경합'})]);
  assert.deepEqual(closeRace.map(r=>r.status).sort(),[200,409],'closing and joining cannot overwrite each other');
  await act('close',{},true);d=await read(true);assert.equal(d.isOpen,false);
  assert.equal((await call({version:d.version,action:'register',names:['닫힘등록']})).status,409);
  d=await act('open',{},true);d=await act('create',{count:1},true);
  const unregisteredBefore=await read(true);
  for(const court of [0,'queue']){
    const response=await call({version:d.version,action:'join',court,names:['미등록']});
    assert.equal(response.status,409);assert.match((await response.json()).error,/참가 명단에 먼저/);
    assert.deepEqual(await read(true),unregisteredBefore);
  }
  for(const names of [[],[''],['가\n나'],['가'.repeat(41)],['가','나','다','라','마'],[42]])assert.equal((await call({version:d.version,action:'register',names})).status,400);
  assert.equal((await call({version:d.version,action:'register',names:['중복등록','중복등록']})).status,409);
  d=await act('register',{names:['  시계가  ','시계나','시계다','시계라'],waitingSince:'2000-01-01T00:00:00.000Z'});
  assert.equal(d.participants.find(p=>p.name==='시계가').waitingSince,d.updatedAt,'only server sets registration time');
  d=await act('register',{names:['시계마','시계바','시계사','시계아']});
  d=await act('register',{names:['시계자']});
  const duplicateBefore=await read(true);
  assert.equal((await call({version:d.version,action:'register',names:['시계가','새미저장']})).status,409);
  assert.deepEqual(await read(true),duplicateBefore,'duplicate batch registration does not reset time or partially add');
  const oldTime='2026-09-16T10:00:00.000Z',fixture=JSON.parse(db.prepare('SELECT payload FROM live_courts WHERE id=1').get().payload);
  fixture.participants.forEach(p=>p.waitingSince=oldTime);
  db.prepare('UPDATE live_courts SET payload=? WHERE id=1').run(JSON.stringify(fixture));
  d=await act('join',{court:0,names:['시계가','시계나','시계다','시계라']});
  assert.equal(d.courts[0].state,'playing');assert.ok(d.participants.every(p=>p.waitingSince===oldTime),'entering play does not reset stored waiting starts');
  d=await act('join',{court:'queue',names:['시계마','시계바','시계사','시계아']});
  d=await act('leave',{court:'queue',group:0,slot:3});
  assert.equal(d.participants.find(p=>p.name==='시계아').waitingSince,oldTime,'queue leave preserves elapsed wait');
  d=await act('join',{court:'queue',group:0,slot:3,names:['시계아']});
  d=await act('end',{court:0});
  assert.deepEqual(d.courts[0].names,['시계마','시계바','시계사','시계아']);
  for(const name of ['시계가','시계나','시계다','시계라'])assert.equal(d.participants.find(p=>p.name===name).waitingSince,d.updatedAt,'outgoing four return at game end');
  for(const name of ['시계마','시계바','시계사','시계아','시계자'])assert.equal(d.participants.find(p=>p.name===name).waitingSince,oldTime,'other waits are not reset');
  assert.deepEqual(await read(),d,'reload preserves exact waiting starts');
  d=await act('create',{count:1},true);
  for(const name of ['시계마','시계바','시계사','시계아'])assert.equal(d.participants.find(p=>p.name===name).waitingSince,d.updatedAt,'cleared active games return to waiting');
  assert.equal(d.participants.find(p=>p.name==='시계자').waitingSince,oldTime);
  d=await act('join',{court:0,names:['시계자']});d=await act('cancel',{court:0});
  assert.equal(d.participants.find(p=>p.name==='시계자').waitingSince,oldTime,'cancelled partial game does not reset wait');
  const registrationRace=await Promise.all([call({version:d.version,action:'register',names:['경합등록']}),call({version:d.version,action:'register',names:['경합등록']})]);
